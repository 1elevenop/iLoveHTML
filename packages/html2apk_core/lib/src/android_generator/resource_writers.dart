/// Escapes text for an XML attribute value or element body.
String xmlEscape(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');

/// Escapes text for an Android `<string>` resource (aapt2 rules on top of XML).
String androidStringEscape(String s) {
  var out = s
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll("'", r"\'")
      .replaceAll('\n', r'\n')
      .replaceAll('\t', r'\t');
  if (out.startsWith('@') || out.startsWith('?')) out = '\\$out';
  return xmlEscape(out).replaceAll('&apos;', "'").replaceAll('&quot;', '"');
}

/// Encodes a `.properties` file (ISO-8859-1 with \uXXXX escapes).
String encodeProperties(Map<String, String> values) {
  String esc(String s, {required bool isKey}) {
    final b = StringBuffer();
    for (var i = 0; i < s.length; i++) {
      final c = s.codeUnitAt(i);
      final ch = s[i];
      if (ch == r'\') {
        b.write(r'\\');
      } else if ('=:#!'.contains(ch) || (ch == ' ' && (isKey || i == 0))) {
        b.write('\\$ch');
      } else if (ch == '\n') {
        b.write(r'\n');
      } else if (ch == '\r') {
        b.write(r'\r');
      } else if (ch == '\t') {
        b.write(r'\t');
      } else if (c < 0x20 || c > 0x7e) {
        b.write('\\u${c.toRadixString(16).padLeft(4, '0')}');
      } else {
        b.write(ch);
      }
    }
    return b.toString();
  }

  final b = StringBuffer('# Generated by html2apk. Do not edit.\n');
  for (final e in values.entries) {
    b.writeln('${esc(e.key, isKey: true)}=${esc(e.value, isKey: false)}');
  }
  return b.toString();
}

String encodeJson(Object? value) => const JsonEncoder.withIndent('  ').convert(value);

class PngInfo {
  const PngInfo(this.width, this.height);

  final int width;
  final int height;
}

/// Reads PNG dimensions from the IHDR chunk, or returns null if [bytes] is not a PNG.
PngInfo? readPngInfo(Uint8List bytes) {
  const sig = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  if (bytes.length < 24) return null;
  for (var i = 0; i < 8; i++) {
    if (bytes[i] != sig[i]) return null;
  }
  if (String.fromCharCodes(bytes.sublist(12, 16)) != 'IHDR') return null;
  final d = ByteData.sublistView(bytes);
  return PngInfo(d.getUint32(16), d.getUint32(20));
}
